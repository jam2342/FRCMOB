import type { TutorialScope } from '../layout/userSettings';

export type TutorialStepPlacement = 'auto' | 'top' | 'right' | 'bottom' | 'left';

export type TutorialWalkthroughStep = {
  id: string;
  // The name of the thing on screen ("Day", "Event Finder").
  system: string;
  title: string;
  description: string;
  tip?: string;
  // `[data-tour="…"]` hooks, not class names: classes get renamed in clean-ups and the tour
  // silently pointed at nothing. tutorialBlueprints.test.ts fails on a hook no page renders.
  selector?: string;
  mobileSelector?: string;
  placement?: TutorialStepPlacement;
  // Skip the step when its target isn't on screen (signed-in only cards, operator panels).
  requiresTarget?: boolean;
  // Phones and desktops lay some pages out differently.
  only?: 'phone' | 'desktop';
};

export type TutorialBlueprint = {
  scope: TutorialScope;
  title: string;
  walkthrough: TutorialWalkthroughStep[];
};

